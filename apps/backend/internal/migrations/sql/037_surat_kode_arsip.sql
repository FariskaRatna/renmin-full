-- R5G10: master kode klasifikasi arsip untuk penomoran surat dinas.
--
-- Sumbernya docs/416270180-Sistem-Penomoran-Surat-Dinas.xlsx, bagian yang
-- memasangkan kode arsip dengan nama perkaranya. Dipakai pada segmen keempat
-- nomor surat: B/ND-157/X/HUM.1.2./2026/Bagrenmin
--                          ^^^^^^^^
-- Petugas mencarinya dengan MENGETIK NAMA ( "buku tamu" ) dan sistem
-- mengembalikan kodenya ( HUM.1.2. ) -- bukan sebaliknya. Karena itu 
-- yang dicari, dan kode cuma hasilnya.
--
-- Referensi, bukan data operasional: tidak ada kepemilikan, tidak ada
-- klasifikasi akses, tidak ada jejak audit. Isinya sama untuk semua unit.
--
-- CATATAN KELENGKAPAN. Berkas sumbernya tampak terpotong di bagian depan:
-- keluarga HUK hanya menyisakan HUK.12.24. s.d. HUK.12.26. yang duduk sebelum
-- blok HUMAS tanpa induk, bentuk khas ekor halaman sebelumnya. Kode HUK.7.1.
-- yang dipakai sebagai contoh di permintaan asli TIDAK ADA di sini. Kekurangan
-- itu ditambahkan lewat migrasi susulan; menambah baris tidak membongkar apa
-- pun di tabel ini.

CREATE TABLE sdl_surat_kode_arsip (
 code VARCHAR(16) PRIMARY KEY CHECK (code ~ '^[A-Z]{2,5}(\.[0-9]+)+\.$'),
 name VARCHAR(250) NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 250),
 -- Prefiks dan kedalaman disimpan, bukan dihitung saat baca: keduanya tetap
 -- sepanjang umur baris, dan menghitungnya di query berarti mengulangi parsing
 -- string yang sama pada tiap pencarian.
 prefix VARCHAR(8) NOT NULL,
 depth SMALLINT NOT NULL CHECK (depth BETWEEN 1 AND 6)
);

-- Pencarian memakai ILIKE '%...%' yang tidak terlayani indeks B-tree, dan atas
-- 701 baris itu memang tidak perlu. Indeks ini untuk menelusuri per keluarga.
CREATE INDEX sdl_surat_kode_arsip_prefix_idx ON sdl_surat_kode_arsip(prefix, code);

